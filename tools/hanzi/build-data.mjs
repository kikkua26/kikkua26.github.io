// ── 拼音交叉校验（可选） ──
function stripTone(p) {
  return p
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace('ü', 'v')
    .replace('ǖ', 'v').replace('ǘ', 'v').replace('ǚ', 'v').replace('ǜ', 'v');
}

function loadDict(dictPath) {
  const map = new Map();
  if (!dictPath || !fs.existsSync(dictPath)) return map;
  const lines = fs.readFileSync(dictPath, 'utf8').split('\n');
  for (const line of lines) {
    if (!line.trim() || !line.startsWith('{')) continue;
    try {
      const o = JSON.parse(line);
      if (o.character && Array.isArray(o.pinyin) && o.pinyin.length) {
        map.set(o.character, o.pinyin[0]);
      }
    } catch { /* skip */ }
  }
  return map;
}

function build(dictPath) {
  const dict = loadDict(dictPath);
  const seen = new Set();
  const mismatches = [];

  const chars = CHARS.map((entry) => {
    if (seen.has(entry.c)) throw new Error(`重复字: ${entry.c}`);
    seen.add(entry.c);
    const dictPinyin = dict.get(entry.c);
    if (dictPinyin && stripTone(dictPinyin) !== stripTone(entry.p)) {
      mismatches.push(`${entry.c} 精选=${entry.p} 字典=${dictPinyin}`);
    }
    return { c: entry.c, p: entry.p, w: entry.w };
  });

  fs.mkdirSync(OUT_DIR, { recursive: true });
  const payload = { version: 2, updated: new Date().toISOString().slice(0, 10), chars };
  fs.writeFileSync(OUT_FILE, JSON.stringify(payload));

  console.log(`已生成 ${OUT_FILE}`);
  console.log(`共 ${chars.length} 字`);
  if (mismatches.length) {
    console.log(`拼音差异 ${mismatches.length} 处（以精选为准）:`);
    mismatches.forEach((m) => console.log('  ' + m));
  }
}

const dictArg = process.argv[2];
build(dictArg);
